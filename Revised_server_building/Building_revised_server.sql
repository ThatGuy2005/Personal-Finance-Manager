CREATE TABLE [Users] (
	[USER_ID] INTEGER NOT NULL IDENTITY,
	[NAME] VARCHAR(255),
	[EMAIL] VARCHAR(255) UNIQUE CHECK(EMAIL LIKE '%_@_%._%'),
	[PASSWORD_HASH] VARCHAR(255),
	PRIMARY KEY([USER_ID])
);
GO

CREATE TABLE [Accounts] (
	[ACCOUNT_ID] INTEGER NOT NULL IDENTITY,
	[PURPOSE_ID] INTEGER,
	[CURRENCY_ID] INTEGER,
	[BALANCE] DECIMAL(18,2),
	[USER_ID] INTEGER,
	PRIMARY KEY([ACCOUNT_ID])
);
GO

CREATE TABLE [Categories] (
	[CATEGORY_ID] INTEGER NOT NULL IDENTITY,
	[NAME] VARCHAR(255) UNIQUE,
	[PRIORITY_ID] INTEGER,
	[DESCRIPTION] VARCHAR(255),
	PRIMARY KEY([CATEGORY_ID])
);
GO

CREATE TABLE [Subcategories] (
	[SUBCATEGORY_ID] INTEGER NOT NULL IDENTITY,
	[CATEGORY_ID] INTEGER,
	[NAME] VARCHAR(255) UNIQUE,
	PRIMARY KEY([SUBCATEGORY_ID])
);
GO

CREATE TABLE [Transactions] (
	[TRANSACTION_ID] INTEGER NOT NULL IDENTITY,
	[TRANSACTION_TIME] DATE,
	[SUBCATEGORY_ID] INTEGER,
	[ACCOUNT_ID] INTEGER,
	[AMOUNT] DECIMAL(18,2),
	[DIRECTION_ID] INTEGER,
	[DESCRIPTION] VARCHAR(255),
	PRIMARY KEY([TRANSACTION_ID]),
	CONSTRAINT [CHK_Transaction_Amount_Direction] CHECK (
		([DIRECTION_ID] = 1 AND [AMOUNT] > 0) OR 
		([DIRECTION_ID] = 2 AND [AMOUNT] < 0)
	)
);
GO

CREATE TABLE [SavingPlans] (
	[SAVING_PLAN_ID] INTEGER NOT NULL IDENTITY,
	[YIELD] DECIMAL(4,2),
	[BUDGET] DECIMAL(18,2),
	[ACCOUNT_ID] INTEGER,
	[SAVING_GOAL_ID] INTEGER,
	PRIMARY KEY([SAVING_PLAN_ID])
);
GO

CREATE TABLE [Currency] (
	[CURRENCY_ID] INTEGER NOT NULL IDENTITY,
	[NAME] CHAR(3) UNIQUE,
	PRIMARY KEY([CURRENCY_ID])
);
GO

CREATE TABLE [Budgets] (
	[BUDGET_ID] INTEGER NOT NULL IDENTITY,
	[BALANCE] DECIMAL(18,2),
	[CATEGORY_ID] INTEGER,
	[PERIOD_BEGIN] DATE,
	[ACCOUNT_ID] INTEGER,
	[PERIOD_END] DATE,
	PRIMARY KEY([BUDGET_ID])
);
GO

CREATE TABLE [RecurringPayments] (
	[RECURRING_PAYMENT_ID] INTEGER NOT NULL IDENTITY,
	[COMPANY_NAME] VARCHAR(255),
	[PRICE] DECIMAL(18,2),
	[SUBCATEGORY_ID] INTEGER,
	[DUE_DATE] DATE,
	[ACCOUNT_ID] INTEGER,
	[FREQUENCY_ID] INTEGER,
	[CURRENCY_ID] INTEGER,
	PRIMARY KEY([RECURRING_PAYMENT_ID])
);
GO

CREATE TABLE [Loans] (
	[LOAN_ID] INTEGER NOT NULL IDENTITY,
	[INTEREST] DECIMAL(5,2),
