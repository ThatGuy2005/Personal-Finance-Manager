);
GO

CREATE TABLE [Budget_Transactions] (
	[BUDGET_ID] INTEGER NOT NULL,
	[TRANSACTION_ID] INTEGER NOT NULL,
	PRIMARY KEY([BUDGET_ID], [TRANSACTION_ID])
);
